-- 1. CONFIGURACIÓN DEL SISTEMA
CREATE TABLE SystemSettings (
    IDSetting INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    KeyName VARCHAR(50) NOT NULL UNIQUE,
    KeyValue VARCHAR(255) NOT NULL,
    Description VARCHAR(255) NULL,
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

-- 2. AUTENTICACIÓN, USUARIOS Y DIRECCIONES (RF-01)
CREATE TABLE Users (
    IDUser VARCHAR(36) NOT NULL PRIMARY KEY,
    Email VARCHAR(255) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    FirstName VARCHAR(100) NOT NULL,
    LastName VARCHAR(100) NOT NULL,
    AvatarURL VARCHAR(500) NULL,
    Role VARCHAR(20) NOT NULL DEFAULT 'Cliente' 
        CHECK (Role IN ('Cliente', 'Operador', 'Administrador')),
    IsActive BIT NOT NULL DEFAULT 1,
    IsVerify BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE TABLE UserSessions (
    IDSession VARCHAR(36) NOT NULL PRIMARY KEY,
    IDUser VARCHAR(36) NOT NULL,
    RefreshToken VARCHAR(500) NOT NULL UNIQUE,
    Family VARCHAR(36) NULL,
    IsRevoked BIT NOT NULL DEFAULT 0,
    ExpiresAt DATETIME2 NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_UserSessions_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser) ON DELETE CASCADE
);

CREATE TABLE Addresses (
    IDAddress VARCHAR(36) NOT NULL PRIMARY KEY,
    IDUser VARCHAR(36) NOT NULL,
    Title VARCHAR(50) NOT NULL,
    RecipientName VARCHAR(150) NOT NULL,
    Phone VARCHAR(20) NOT NULL,
    StreetAddress VARCHAR(255) NOT NULL,
    City VARCHAR(100) NOT NULL,
    State VARCHAR(100) NOT NULL,
    PostalCode VARCHAR(20) NULL,
    IsDefault BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Addresses_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser) ON DELETE CASCADE
);

-- 3. CATÁLOGO DE PRODUCTOS, IMÁGENES Y VARIANTES (RF-02)
CREATE TABLE Categories (
    IDCategory VARCHAR(36) NOT NULL PRIMARY KEY,
    Name VARCHAR(100) NOT NULL UNIQUE,
    Description VARCHAR(255) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Products (
    IDProduct VARCHAR(36) NOT NULL PRIMARY KEY,
    IDCategory VARCHAR(36) NOT NULL,
    Name VARCHAR(200) NOT NULL,
    Description NVARCHAR(MAX) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Products_Categories FOREIGN KEY (IDCategory) REFERENCES Categories(IDCategory)
);

CREATE TABLE ProductImages (
    IDImage VARCHAR(36) NOT NULL PRIMARY KEY,
    IDProduct VARCHAR(36) NOT NULL,
    ImageURL VARCHAR(500) NOT NULL,
    SortOrder INT NOT NULL DEFAULT 0,
    IsCover BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_ProductImages_Products FOREIGN KEY (IDProduct) REFERENCES Products(IDProduct) ON DELETE CASCADE
);

CREATE TABLE ProductVariants (
    IDVariant VARCHAR(36) NOT NULL PRIMARY KEY,
    IDProduct VARCHAR(36) NOT NULL,
    SKU VARCHAR(60) NOT NULL UNIQUE,
    Attributes NVARCHAR(MAX) NULL, -- JSON ej: {"talla": "M", "color": "Rojo"}
    Price DECIMAL(12, 2) NOT NULL CHECK (Price >= 0),
    StockPhysical INT NOT NULL DEFAULT 0 CHECK (StockPhysical >= 0),
    StockReserved INT NOT NULL DEFAULT 0 CHECK (StockReserved >= 0),
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_ProductVariants_Products FOREIGN KEY (IDProduct) REFERENCES Products(IDProduct),
    CONSTRAINT CK_Stock_Limit CHECK (StockReserved <= StockPhysical)
);

-- 4. KARDEX E INVENTARIO (RF-03)
CREATE TABLE KardexMovements (
    IDKardex VARCHAR(36) NOT NULL PRIMARY KEY,
    IDVariant VARCHAR(36) NOT NULL,
    IDUser VARCHAR(36) NULL,
    MovementType VARCHAR(20) NOT NULL CHECK (MovementType IN ('ENTRADA', 'SALIDA', 'AJUSTE', 'DEVOLUCION')),
    Quantity INT NOT NULL,
    PreviousStock INT NOT NULL,
    NewStock INT NOT NULL,
    Reason NVARCHAR(255) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_KardexMovements_Variants FOREIGN KEY (IDVariant) REFERENCES ProductVariants(IDVariant),
    CONSTRAINT FK_KardexMovements_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser)
);

-- 5. CARRITO DE COMPRAS Y RESERVAS TEMPORALES (RF-04, RF-06)
CREATE TABLE Carts (
    IDCart VARCHAR(36) NOT NULL PRIMARY KEY,
    IDUser VARCHAR(36) NULL,
    GuestToken VARCHAR(255) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Carts_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser) ON DELETE CASCADE
);

CREATE UNIQUE NONCLUSTERED INDEX UQ_Carts_IDUser ON Carts(IDUser) WHERE IDUser IS NOT NULL;
CREATE UNIQUE NONCLUSTERED INDEX UQ_Carts_GuestToken ON Carts(GuestToken) WHERE GuestToken IS NOT NULL;

CREATE TABLE CartItems (
    IDCartItem VARCHAR(36) NOT NULL PRIMARY KEY,
    IDCart VARCHAR(36) NOT NULL,
    IDVariant VARCHAR(36) NOT NULL,
    Quantity INT NOT NULL CHECK (Quantity > 0),
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT UQ_CartItem_Variant UNIQUE (IDCart, IDVariant),
    CONSTRAINT FK_CartItems_Carts FOREIGN KEY (IDCart) REFERENCES Carts(IDCart) ON DELETE CASCADE,
    CONSTRAINT FK_CartItems_Variants FOREIGN KEY (IDVariant) REFERENCES ProductVariants(IDVariant)
);

CREATE TABLE StockReservations (
    IDReservation VARCHAR(36) NOT NULL PRIMARY KEY,
    IDVariant VARCHAR(36) NOT NULL,
    IDCart VARCHAR(36) NOT NULL,
    Quantity INT NOT NULL CHECK (Quantity > 0),
    ExpiresAt DATETIME2 NOT NULL,
    IsReleased BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_StockReservations_Variants FOREIGN KEY (IDVariant) REFERENCES ProductVariants(IDVariant),
    CONSTRAINT FK_StockReservations_Carts FOREIGN KEY (IDCart) REFERENCES Carts(IDCart)
);

-- 6. CUPONES Y PROMOCIONES (RF-05)
CREATE TABLE Coupons (
    IDCoupon VARCHAR(36) NOT NULL PRIMARY KEY,
    Code VARCHAR(50) NOT NULL UNIQUE,
    DiscountType VARCHAR(20) NOT NULL CHECK (DiscountType IN ('PORCENTAJE', 'MONTO_FIJO')),
    DiscountValue DECIMAL(12, 2) NOT NULL CHECK (DiscountValue > 0),
    MinOrderAmount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    MaxUses INT NOT NULL,
    CurrentUses INT NOT NULL DEFAULT 0,
    MaxUsesPerClient INT NOT NULL DEFAULT 1,
    IDCategory VARCHAR(36) NULL,
    StartsAt DATETIME2 NOT NULL,
    ExpiresAt DATETIME2 NOT NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Coupons_Categories FOREIGN KEY (IDCategory) REFERENCES Categories(IDCategory)
);

CREATE TABLE CouponUsages (
    IDCouponUsage VARCHAR(36) NOT NULL PRIMARY KEY,
    IDCoupon VARCHAR(36) NOT NULL,
    IDUser VARCHAR(36) NOT NULL,
    IDOrder VARCHAR(36) NOT NULL,
    UsedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_CouponUsages_Coupons FOREIGN KEY (IDCoupon) REFERENCES Coupons(IDCoupon),
    CONSTRAINT FK_CouponUsages_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser)
);

-- 7. PEDIDOS, DETALLES E IDEMPOTENCIA (RF-06, RF-07)
CREATE TABLE Orders (
    IDOrder VARCHAR(36) NOT NULL PRIMARY KEY,
    OrderNumber VARCHAR(30) NOT NULL UNIQUE,
    IDUser VARCHAR(36) NOT NULL,
    IDAddress VARCHAR(36) NOT NULL,
    IDCoupon VARCHAR(36) NULL,
    IdempotencyKey VARCHAR(100) NOT NULL UNIQUE,
    Status VARCHAR(30) NOT NULL DEFAULT 'CREADO'
        CHECK (Status IN ('CREADO', 'PAGADO', 'PREPARACION', 'DESPACHADO', 'ENTREGADO', 'CANCELADO', 'DEVUELTO')),
    Subtotal DECIMAL(12, 2) NOT NULL CHECK (Subtotal >= 0),
    Discount DECIMAL(12, 2) NOT NULL DEFAULT 0.00 CHECK (Discount >= 0),
    Total DECIMAL(12, 2) NOT NULL CHECK (Total >= 0),
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Orders_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser),
    CONSTRAINT FK_Orders_Coupons FOREIGN KEY (IDCoupon) REFERENCES Coupons(IDCoupon),
    CONSTRAINT FK_Orders_Addresses FOREIGN KEY (IDAddress) REFERENCES Addresses(IDAddress)
);

CREATE TABLE OrderItems (
    IDOrderItem VARCHAR(36) NOT NULL PRIMARY KEY,
    IDOrder VARCHAR(36) NOT NULL,
    IDVariant VARCHAR(36) NOT NULL,
    ProductName VARCHAR(200) NOT NULL,
    VariantSKU VARCHAR(60) NOT NULL,
    UnitPrice DECIMAL(12, 2) NOT NULL CHECK (UnitPrice >= 0),
    Quantity INT NOT NULL CHECK (Quantity > 0),
    ReturnedQuantity INT NOT NULL DEFAULT 0 CHECK (ReturnedQuantity >= 0),
    Subtotal DECIMAL(12, 2) NOT NULL,
    CONSTRAINT FK_OrderItems_Orders FOREIGN KEY (IDOrder) REFERENCES Orders(IDOrder) ON DELETE CASCADE,
    CONSTRAINT FK_OrderItems_Variants FOREIGN KEY (IDVariant) REFERENCES ProductVariants(IDVariant),
    CONSTRAINT CK_OrderItems_ReturnedLimit CHECK (ReturnedQuantity <= Quantity)
);

CREATE TABLE OrderStatusHistory (
    IDStatusHistory VARCHAR(36) NOT NULL PRIMARY KEY,
    IDOrder VARCHAR(36) NOT NULL,
    IDUser VARCHAR(36) NULL,
    PreviousStatus VARCHAR(30) NULL,
    NewStatus VARCHAR(30) NOT NULL,
    ChangedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_OrderStatusHistory_Orders FOREIGN KEY (IDOrder) REFERENCES Orders(IDOrder),
    CONSTRAINT FK_OrderStatusHistory_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser)
);

CREATE TABLE OrderReturns (
    IDReturn VARCHAR(36) NOT NULL PRIMARY KEY,
    IDOrder VARCHAR(36) NOT NULL,
    IDOrderItem VARCHAR(36) NOT NULL,
    IDUser VARCHAR(36) NOT NULL,
    Quantity INT NOT NULL CHECK (Quantity > 0),
    Reason NVARCHAR(255) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_OrderReturns_Orders FOREIGN KEY (IDOrder) REFERENCES Orders(IDOrder),
    CONSTRAINT FK_OrderReturns_OrderItems FOREIGN KEY (IDOrderItem) REFERENCES OrderItems(IDOrderItem),
    CONSTRAINT FK_OrderReturns_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser)
);

-- 8. BITÁCORA DE AUDITORÍA INMUTABLE (RF-09)
CREATE TABLE AuditLogs (
    IDAuditLog VARCHAR(36) NOT NULL PRIMARY KEY,
    IDUser VARCHAR(36) NULL,
    Entity VARCHAR(50) NOT NULL,
    Action VARCHAR(50) NOT NULL,
    OldValue NVARCHAR(MAX) NULL,
    NewValue NVARCHAR(MAX) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_AuditLogs_Users FOREIGN KEY (IDUser) REFERENCES Users(IDUser)
);
