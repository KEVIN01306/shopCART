-- BASE DE DATOS: RETO SHOPCART (COMPLETO Y AJUSTADO A LOS ESTÁNDARES)
-- Motor: Microsoft SQL Server 2019+
-- Cumple: RF-01 a RF-09, estándares de nomenclatura, inmutabilidad y tipos estrictos
